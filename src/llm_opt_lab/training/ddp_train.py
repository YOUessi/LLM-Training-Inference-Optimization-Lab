"""Synthetic PyTorch DDP training benchmark. Not actual LLM pretraining."""
from __future__ import annotations
import argparse
import hashlib
import os
import statistics
import sys
import time
from pathlib import Path
from llm_opt_lab.provenance import environment, write_json_atomic


def model_sha256(model) -> str:
    """Hash exact model state including key names, shapes, dtypes and bytes."""
    h = hashlib.sha256()
    for name, tensor in sorted(model.state_dict().items()):
        x = tensor.detach().cpu().contiguous()
        h.update(name.encode("utf-8"))
        h.update(str(tuple(x.shape)).encode("ascii"))
        h.update(str(x.dtype).encode("ascii"))
        h.update(x.numpy().tobytes())
    return h.hexdigest()


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--steps",type=int,default=25)
    p.add_argument("--batch-size",type=int,default=32)
    p.add_argument("--features",type=int,default=256)
    p.add_argument("--hidden",type=int,default=512)
    p.add_argument("--seed",type=int,default=2026)
    p.add_argument("--lr",type=float,default=1e-3)
    p.add_argument("--device",choices=("cpu","cuda"),default="cpu")
    p.add_argument("--resume",type=Path)
    p.add_argument("--checkpoint",type=Path)
    p.add_argument("--output",type=Path,default=Path("results/ddp_train.json"))
    a=p.parse_args(argv)
    if min(a.steps,a.batch_size,a.features,a.hidden)<=0 or a.lr<=0:
        p.error("steps, batch-size, features, hidden and lr must be positive")
    return a


def main(argv: list[str] | None = None) -> int:
    a=parse_args(argv)
    try:
        import torch
        import torch.distributed as dist
        from torch import nn
        from torch.nn.parallel import DistributedDataParallel as DDP
    except ImportError as exc:
        print(f"BLOCKED: install PyTorch in a dedicated environment: {exc}",file=sys.stderr)
        return 2
    keys=("RANK","WORLD_SIZE","LOCAL_RANK","MASTER_ADDR","MASTER_PORT")
    if not all(k in os.environ for k in keys):
        print("BLOCKED: launch with torchrun, not plain python",file=sys.stderr)
        return 2
    rank,world_size,local_rank=(int(os.environ[k]) for k in keys[:3])
    if a.device=="cuda":
        if not torch.cuda.is_available() or local_rank>=torch.cuda.device_count():
            print("BLOCKED: requested CUDA rank without visible GPU",file=sys.stderr)
            return 2
        torch.cuda.set_device(local_rank)
        device=torch.device("cuda",local_rank)
        backend="nccl"
    else:
        device=torch.device("cpu")
        backend="gloo"

    dist.init_process_group(backend=backend,init_method="env://")
    try:
        torch.manual_seed(a.seed+rank)
        model=nn.Sequential(nn.Linear(a.features,a.hidden),
                            nn.GELU(),nn.Linear(a.hidden,a.features)).to(device)
        ddp=DDP(model,device_ids=[local_rank] if a.device=="cuda" else None)
        optimizer=torch.optim.AdamW(ddp.parameters(),lr=a.lr)
        initial_step=0
        if a.resume:
            # Only checkpoint files generated by this lab should be used.
            ckpt=torch.load(a.resume,map_location="cpu",weights_only=True)
            if ckpt.get("checkpoint_version")!=2:
                raise ValueError("checkpoint does not capture per-rank RNG states")
            if ckpt.get("world_size")!=world_size or ckpt.get("device_type")!=a.device:
                raise ValueError("checkpoint distributed world size or device type mismatch")
            if ckpt.get("seed")!=a.seed:
                raise ValueError("checkpoint training seed mismatch")
            if ckpt.get("config")!=[a.features,a.hidden,a.batch_size]:
                raise ValueError("resume checkpoint model/batch configuration mismatch")
            ddp.module.load_state_dict(ckpt["model"])
            optimizer.load_state_dict(ckpt["optimizer"])
            initial_step=int(ckpt["steps_completed"])
            if initial_step>=a.steps:
                raise ValueError("target steps must exceed checkpoint steps_completed")
        gen=torch.Generator(device=device)
        gen.manual_seed(a.seed+10000+rank)
        if a.resume:
            states=ckpt["rank_rng_states"]
            if len(states)!=world_size:
                raise ValueError("incomplete per-rank RNG states in checkpoint")
            state=states[rank]
            gen.set_state(state["data_generator"].cpu())
            torch.set_rng_state(state["torch_cpu_rng"].cpu())
            if a.device=="cuda":
                torch.cuda.set_rng_state(state["torch_cuda_rng"].cpu(),device=device)
        dist.barrier()
        times=[]
        final_loss=None
        for step in range(initial_step,a.steps):
            x=torch.randn((a.batch_size,a.features),device=device,generator=gen)
            y=0.5*x
            if a.device=="cuda":
                torch.cuda.synchronize()
            start=time.perf_counter()
            optimizer.zero_grad(set_to_none=True)
            loss=(ddp(x)-y).square().mean()
            loss.backward()
            optimizer.step()
            if a.device=="cuda":
                torch.cuda.synchronize()
            times.append(time.perf_counter()-start)
            final_loss=float(loss.detach().item())
        elapsed_local=sum(times)
        elapsed_max=torch.tensor(elapsed_local,device=device,dtype=torch.float64)
        dist.all_reduce(elapsed_max,op=dist.ReduceOp.MAX)
        slowest=float(elapsed_max.item())
        if a.checkpoint:
            own_rng={
                "data_generator":gen.get_state(),
                "torch_cpu_rng":torch.get_rng_state(),
                "torch_cuda_rng":torch.cuda.get_rng_state(device=device)
                    if a.device=="cuda" else None,
            }
            states=[None]*world_size
            dist.all_gather_object(states,own_rng)
            dist.barrier()
            if rank==0:
                a.checkpoint.parent.mkdir(parents=True,exist_ok=True)
                tmp=a.checkpoint.with_name(a.checkpoint.name+".tmp-"+str(os.getpid()))
                try:
                    torch.save({
                        "checkpoint_version":2,
                        "world_size":world_size,
                        "device_type":a.device,
                        "rank_rng_states":states,
                        "model":ddp.module.state_dict(),
                        "optimizer":optimizer.state_dict(),
                        "steps_completed":a.steps,
                        "config":[a.features,a.hidden,a.batch_size],
                        "seed":a.seed,
                    },tmp)
                    os.replace(tmp,a.checkpoint)
                finally:
                    tmp.unlink(missing_ok=True)
            dist.barrier()
        if rank==0:
            measured=a.steps-initial_step
            result={
                "status":"measured",
                "kind":"synthetic_ddp_training",
                "not_an_llm_training_result":True,
                "config":{
                    "world_size":world_size,"device":a.device,"backend":backend,
                    "completed_steps":a.steps,"steps_measured":measured,
                    "batch_size_per_rank":a.batch_size,"features":a.features,
                    "hidden":a.hidden,"lr":a.lr,"seed":a.seed,"resumed":bool(a.resume),
                    "checkpoint_version":2,
                },
                "environment":environment(),
                "results":{
                    "last_loss":final_loss,
                    "model_sha256":model_sha256(ddp.module),
                    "median_local_step_ms":statistics.median(times)*1000.,
                    "p95_local_step_ms":sorted(times)[min(len(times)-1,int(0.95*len(times)))]*1000.,
                    "slowest_rank_total_step_time_s":slowest,
                    "throughput_samples_per_s":a.batch_size*world_size*measured/slowest if slowest>0 else None,
                },
            }
            write_json_atomic(a.output,result)
            print("DDP steps completed:",measured,"world_size:",world_size)
        return 0
    finally:
        dist.destroy_process_group()


if __name__=="__main__":
    raise SystemExit(main())
